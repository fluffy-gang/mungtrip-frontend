import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const source = fs.readFileSync(new URL('../src/features/app-integration/sheet-request.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(output, { exports: module.exports, module });
const { createSheetRequest } = module.exports;
const request = createSheetRequest(input => ({ status: 'cancelled', source: input.source }));
let changes = 0;
const unsubscribe = request.subscribe(() => { changes++; });
const input = { source: 'mock', placeId: 101 };
const first = request.open(input);
const firstSnapshot = request.getSnapshot();
assert.equal(request.getSnapshot(), firstSnapshot);
assert.equal(firstSnapshot.input, input);
const duplicate = await request.open({ source: 'mock', placeId: 102 });
assert.equal(duplicate.status, 'cancelled');
assert.equal(request.getSnapshot(), firstSnapshot);
request.cancel();
assert.equal((await first).status, 'cancelled');
assert.equal(request.getSnapshot(), null);
const second = request.open({ source: 'real', placeId: 36 });
const secondSnapshot = request.getSnapshot();
request.finish(firstSnapshot.id, { status: 'completed', source: 'mock' });
assert.equal(request.getSnapshot(), secondSnapshot, 'late old-session sheet cannot complete the new request');
request.finish(secondSnapshot.id, { status: 'completed', source: 'real' });
assert.equal((await second).source, 'real');
assert.equal(request.getSnapshot(), null);
assert.equal(changes, 4);
unsubscribe();
request.cancel();
assert.equal(changes, 4);
console.log('integration sheet requests: duplicate input, cancellation, source change, late completion, stable snapshots PASS');
